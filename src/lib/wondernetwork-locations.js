// Helper function to find WonderNetwork location by city name
export function findWonderNetworkLocation(cityName) {
  if (!cityName) return null;

  // Clean up the search term - remove state codes, country names, extra whitespace
  let searchTerm = cityName.toLowerCase().trim();

  // Remove common patterns like ", CA", ", NY", ", USA", etc.
  searchTerm = searchTerm
    .replace(/,\s*[a-z]{2}$/i, '') // Remove ", XX" state codes at end
    .replace(/,\s*usa$/i, '')      // Remove ", USA"
    .replace(/,\s*us$/i, '')       // Remove ", US"
    .replace(/,\s*united states$/i, '') // Remove ", United States"
    .trim();

  // Direct name match
  const directMatch = WONDERNETWORK_LOCATIONS.find(
    loc => loc.name.toLowerCase() === searchTerm
  );

  if (directMatch) {
    return {
      serverName: directMatch.name.toLowerCase().replace(/\s+/g, '-'),
      displayName: directMatch.name,
      country: directMatch.country
    };
  }

  // Location match
  const locationMatch = WONDERNETWORK_LOCATIONS.find(
    loc => loc.location.toLowerCase() === searchTerm
  );

  if (locationMatch) {
    return {
      serverName: locationMatch.name.toLowerCase().replace(/\s+/g, '-'),
      displayName: locationMatch.name,
      country: locationMatch.country
    };
  }

  // Partial match
  const partialMatch = WONDERNETWORK_LOCATIONS.find(
    loc => loc.name.toLowerCase().includes(searchTerm) ||
           loc.location.toLowerCase().includes(searchTerm)
  );

  if (partialMatch) {
    return {
      serverName: partialMatch.name.toLowerCase().replace(/\s+/g, '-'),
      displayName: partialMatch.name,
      country: partialMatch.country
    };
  }

  return null;
}
